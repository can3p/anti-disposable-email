// Command update-lists regenerates the embedded domain lists in data/ from the
// upstream sources described in data/SOURCES.md.
//
// Run it from the repository root:
//
//	go run ./cmd/update-lists
//
// It only uses the standard library and this package, so it adds no
// dependencies for projects that import the library.
package main

import (
	"bufio"
	"context"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	disposable "github.com/can3p/anti-disposable-email"
	"golang.org/x/net/idna"
)

type source struct {
	name string
	url  string
	// min is the smallest plausible number of domains. A smaller download
	// means the source broke or changed format, and the update is aborted.
	min int
}

var blocklists = []source{
	{"disposable-email-domains", "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf", 5000},
	{"disposable/disposable", "https://raw.githubusercontent.com/disposable/disposable-email-domains/master/domains.txt", 50000},
	{"mailchecker", "https://raw.githubusercontent.com/FGRibreau/mailchecker/master/list.txt", 20000},
	{"burner-email-providers", "https://raw.githubusercontent.com/wesbos/burner-email-providers/master/emails.txt", 10000},
	{"fakefilter", "https://raw.githubusercontent.com/7c/fakefilter/main/txt/data.txt", 1000},
}

// The disposable/disposable project publishes "disposable + forwarding" as a
// separate list. Subtracting its disposable-only list leaves the forwarding
// and alias services.
var (
	forwardingPlusDisposable = source{"disposable/disposable forwarding", "https://raw.githubusercontent.com/disposable/disposable-email-domains/master/domains_forwarding.txt", 50000}
	disposableOnly           = blocklists[1]
	upstreamAllow            = source{"disposable/disposable whitelist", "https://raw.githubusercontent.com/disposable/disposable/master/whitelist.txt", 20}
)

const header = "# Generated by cmd/update-lists on %s. Do not edit by hand.\n# Sources and licenses: see SOURCES.md.\n"

func main() {
	dir := flag.String("dir", "data", "directory holding the data files")
	force := flag.Bool("force", false, "write the lists even if the disposable list shrinks by more than 20%")
	flag.Parse()

	if err := run(*dir, *force); err != nil {
		log.Fatal(err)
	}
}

func run(dir string, force bool) error {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()

	// Allowlist: upstream plus our hand-maintained file.
	allow, err := fetch(ctx, upstreamAllow)
	if err != nil {
		return err
	}
	local, err := readLocal(filepath.Join(dir, "allowlist_local.txt"))
	if err != nil {
		return err
	}
	for d := range local {
		allow[d] = struct{}{}
	}

	// Relay: forwarding services that are not disposable.
	fwd, err := fetch(ctx, forwardingPlusDisposable)
	if err != nil {
		return err
	}
	only, err := fetch(ctx, disposableOnly)
	if err != nil {
		return err
	}
	relay := map[string]struct{}{}
	for d := range fwd {
		if _, ok := only[d]; ok {
			continue
		}
		if _, ok := allow[d]; ok {
			continue
		}
		relay[d] = struct{}{}
	}
	if len(relay) < 20 {
		return fmt.Errorf("relay list has only %d domains; the forwarding source probably changed", len(relay))
	}

	// Disposable: union of all blocklists, minus allowed and relay domains.
	disp := map[string]struct{}{}
	for _, src := range blocklists {
		set := only
		if src != disposableOnly {
			if set, err = fetch(ctx, src); err != nil {
				return err
			}
		}
		for d := range set {
			disp[d] = struct{}{}
		}
	}
	removedAllow, removedRelay := 0, 0
	for d := range disp {
		if _, ok := allow[d]; ok {
			delete(disp, d)
			removedAllow++
		} else if _, ok := relay[d]; ok {
			delete(disp, d)
			removedRelay++
		}
	}
	log.Printf("disposable: %d domains (%d dropped as allowlisted, %d moved to relay)", len(disp), removedAllow, removedRelay)
	log.Printf("relay: %d domains, allowlist: %d domains", len(relay), len(allow))

	dispPath := filepath.Join(dir, "disposable.txt")
	if prev, err := countLines(dispPath); err == nil && !force && float64(len(disp)) < 0.8*float64(prev) {
		return fmt.Errorf("disposable list would shrink from %d to %d domains; rerun with -force if this is expected", prev, len(disp))
	}

	for path, set := range map[string]map[string]struct{}{
		dispPath:                            disp,
		filepath.Join(dir, "relay.txt"):     relay,
		filepath.Join(dir, "allowlist.txt"): allow,
	} {
		if err := write(path, set); err != nil {
			return err
		}
	}
	return nil
}

func fetch(ctx context.Context, src source) (map[string]struct{}, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, src.url, nil)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", src.name, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s returned %s", src.name, src.url, resp.Status)
	}
	set, skipped, err := parse(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", src.name, err)
	}
	if len(set) < src.min {
		return nil, fmt.Errorf("%s: only %d domains, expected at least %d", src.name, len(set), src.min)
	}
	log.Printf("%s: %d domains (%d invalid lines skipped)", src.name, len(set), skipped)
	return set, nil
}

func readLocal(path string) (map[string]struct{}, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	set, skipped, err := parse(f)
	if err != nil {
		return nil, err
	}
	if skipped > 0 {
		return nil, fmt.Errorf("%s: %d invalid lines", path, skipped)
	}
	return set, nil
}

// parse reads one domain per line, ignoring blank lines and '#' comments.
// Invalid domains are counted and skipped.
func parse(r io.Reader) (map[string]struct{}, int, error) {
	set := map[string]struct{}{}
	skipped := 0
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(line)), ".")
		if line == "" {
			continue
		}
		d, err := idna.ToASCII(line)
		if err != nil || !disposable.ValidateDomain(d) {
			skipped++
			continue
		}
		set[d] = struct{}{}
	}
	return set, skipped, sc.Err()
}

func countLines(path string) (int, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	set, _, err := parse(f)
	return len(set), err
}

func write(path string, set map[string]struct{}) error {
	list := make([]string, 0, len(set))
	for d := range set {
		list = append(list, d)
	}
	sort.Strings(list)

	var b strings.Builder
	fmt.Fprintf(&b, header, time.Now().UTC().Format("2006-01-02"))
	for _, d := range list {
		b.WriteString(d)
		b.WriteByte('\n')
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
